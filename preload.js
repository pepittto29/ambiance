const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ambiance', {
  info: () => ipcRenderer.invoke('info'),
  setCompact: (on) => ipcRenderer.invoke('set-compact', on),
  setFullscreen: (on) => ipcRenderer.invoke('set-fullscreen', on),
  setOpenAtLogin: (on) => ipcRenderer.invoke('set-open-at-login', on),
  setConfig: (patch) => ipcRenderer.invoke('set-config', patch),
  pickBurrow: () => ipcRenderer.invoke('pick-burrow'),
  getModes: () => ipcRenderer.invoke('modes-get'),
  activateMode: (id) => ipcRenderer.invoke('mode-activate', id),
  saveMode: (mode) => ipcRenderer.invoke('mode-save', mode),
  deleteMode: (id) => ipcRenderer.invoke('mode-delete', id),
  runningApps: () => ipcRenderer.invoke('running-apps'),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  onModeChanged: (cb) => ipcRenderer.on('mode-changed', (_e, m) => cb(m)),
  tasks: {
    get: () => ipcRenderer.invoke('tasks-get'),
    add: (t) => ipcRenderer.invoke('tasks-add', t),
    update: (id, patch) => ipcRenderer.invoke('tasks-update', id, patch),
    remove: (id) => ipcRenderer.invoke('tasks-remove', id),
    clearDone: () => ipcRenderer.invoke('tasks-clear-done'),
    importLegacy: (items) => ipcRenderer.invoke('tasks-import', items),
    onChange: (cb) => ipcRenderer.on('tasks-changed', (_e, list) => cb(list)),
  },
  sendFocusState: (s) => ipcRenderer.send('focus-state', s),
  onNavigate: (cb) => ipcRenderer.on('navigate', (_e, page) => cb(page)),
  setPlaying: (on) => ipcRenderer.send('playing', on),
  onTogglePlay: (cb) => ipcRenderer.on('toggle-play', () => cb()),
  onPause: (cb) => ipcRenderer.on('pause', () => cb()),
  onConfig: (cb) => ipcRenderer.on('config', (_e, c) => cb(c)),
  importSounds: () => ipcRenderer.invoke('import-sounds'),
  readSound: (file) => ipcRenderer.invoke('read-sound', file),
  readBuiltin: (name) => ipcRenderer.invoke('read-builtin', name),
  deleteSound: (file) => ipcRenderer.invoke('delete-sound', file),
});
